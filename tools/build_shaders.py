#!/usr/bin/env python3
"""Compile renderer/shaders.hlsl to D3D9 bytecode and write renderer/shaders.cxx.

Needs a D3DCompile-capable compiler: on Linux, Wine + tools/fxc (built from tools/fxc.c),
on Windows, fxc.exe from the Windows SDK (pass --fxc fxc.exe).
"""
import os, subprocess, sys, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "renderer", "shaders.hlsl")
fxc = sys.argv[sys.argv.index("--fxc") + 1] if "--fxc" in sys.argv else None
entries = [("vs_main", "vs_3_0"), ("ps_main", "ps_3_0"), ("vs_blit", "vs_3_0"), ("ps_blit", "ps_3_0")]
out = ["// generated by tools/build_shaders.py from shaders.hlsl - do not edit", '#include "shaders.hxx"', ""]
hlsl = open(src).read()
out.append("const char SHADER_SOURCE[] =")
for line in hlsl.splitlines():
    out.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
out.append(";\n")
with tempfile.TemporaryDirectory() as tmp:
    for entry, profile in entries:
        dst = os.path.join(tmp, entry + ".bin")
        if fxc and fxc.lower().endswith("fxc.exe") and os.name == "nt":
            cmd = [fxc, "/nologo", "/T", profile, "/E", entry, "/Fo", dst, src]
        else:
            cmd = ["wine", fxc or os.path.join(root, "tools", "fxc", "fxc.exe"), src, entry, profile, dst]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if not os.path.exists(dst):
            sys.exit(f"{entry}: {r.stdout}{r.stderr}")
        data = open(dst, "rb").read()
        out.append(f"const unsigned char g_{entry}[] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};\n")
        print(entry, len(data), "bytes")
open(os.path.join(root, "renderer", "shaders.cxx"), "w").write("\n".join(out))
